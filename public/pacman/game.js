const startIfNeeded = () => {
    if (started || gameOver) return;
    started = true;   // le chronomètre du serveur démarre ici
    window.parent.postMessage({ type: "pacman:started" }, window.location.origin);
};

const turn = (direction) => {
    if (gameOver) return;
    startIfNeeded();
    pacman.nextDirection = direction;
};

window.addEventListener("keydown", (event) => {
    const k = event.keyCode;
    if ([37, 38, 39, 40, 65, 87, 68, 83].includes(k)) event.preventDefault();
    if (k == 37 || k == 65) turn(DIRECTION_LEFT);
    else if (k == 38 || k == 87) turn(DIRECTION_UP);
    else if (k == 39 || k == 68) turn(DIRECTION_RIGHT);
    else if (k == 40 || k == 83) turn(DIRECTION_BOTTOM);
});

// Tactile : glisser le doigt dans la direction voulue
let touchStart = null;
canvas.addEventListener("touchstart", (e) => { touchStart = e.touches[0]; e.preventDefault(); }, { passive: false });
canvas.addEventListener("touchend", (e) => {
    if (!touchStart) return;
    const t = e.changedTouches[0];
    const dx = t.clientX - touchStart.clientX;
    const dy = t.clientY - touchStart.clientY;
    touchStart = null;
    if (Math.max(Math.abs(dx), Math.abs(dy)) < 20) return;
    if (Math.abs(dx) > Math.abs(dy)) turn(dx > 0 ? DIRECTION_RIGHT : DIRECTION_LEFT);
    else turn(dy > 0 ? DIRECTION_BOTTOM : DIRECTION_UP);
});
